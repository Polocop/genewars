import importlib.util,pathlib,unittest
ROOT=pathlib.Path(__file__).resolve().parents[1]; P=ROOT/'tools/probes/unicorn_int21.py'
spec=importlib.util.spec_from_file_location('unicorn_services_probe',P); probe=importlib.util.module_from_spec(spec); spec.loader.exec_module(probe)
class UnicornServiceTests(unittest.TestCase):
 def test_int2f_mscdex_check_reports_only_configured_inventory(self):
  boot=probe.prepare_guest(ROOT/'evidence'/'genewars-1_1.exe')
  host=probe.DosHost(boot)
  regs=probe.CpuRegs(eax=0x1500,ebx=0x12340000,ecx=0x56780000,eflags=0x202)
  result=host.dispatch(0x2f,regs)
  self.assertTrue(result.handled); self.assertEqual(result.service,'int2f.mscdex_install_check')
  self.assertEqual((regs.ax,regs.bx,regs.cx),(0x1500,0,0))
  configured=probe.DosHost(boot,cdrom_drives=('D','E'))
  regs=probe.CpuRegs(eax=0x1500,ebx=0,ecx=0)
  self.assertTrue(configured.dispatch(0x2f,regs).handled)
  self.assertEqual((regs.bx,regs.cx),(2,3))
