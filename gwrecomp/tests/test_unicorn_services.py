 def test_dos4gw_ah48_pointer_is_aliased_and_ah49_translates_back(self):
  boot=probe.prepare_guest(ROOT/'evidence'/'genewars-1_1.exe')
  host=probe.DosHost(boot,dos_memory_profile='post_dos4gw_le_entry')
  uc=probe.Uc(probe.UC_ARCH_X86,probe.UC_MODE_32)
  uc.mem_map(0x1000,0xff000,probe.UC_PROT_ALL)
  self.assertTrue(probe.write_flat_gdt(uc,{},boot.psp_address))
  code=bytes.fromhex('66b8004866bb0100cd218ec0b449cd21f4')
  uc.mem_write(probe.SYNTH_ADDRESS,code)
  trace={}; probe.install_trace_hooks(uc,trace,100,host)
  uc.emu_start(probe.SYNTH_ADDRESS,0xffffffff,timeout=1_000_000,count=100)
  self.assertEqual([i['service'] for i in trace['interrupts']],['dos21.allocate_memory','dos21.free_memory'])
  alloc,free=trace['interrupts']
  selector=int(alloc['registers_after']['eax'],16)
  self.assertEqual(alloc['registers_after']['eax'],f'0x{selector:08x}')
  self.assertNotEqual(selector,int(alloc['registers_after']['ebx'],16))
  self.assertEqual(free['es'],f'0x{selector:04x}')
  self.assertFalse(free['registers_after']['eflags'] and int(free['registers_after']['eflags'],16)&1)
  self.assertNotIn(selector,host.dos_ah48_selectors)
  self.assertNotIn(selector,host.selectors)
  self.assertFalse(host.dos_ah48_allocations)
  self.assertIsNone(trace.get('guest_exception'))

