 def test_dpmi_allocation_pages_are_mapped_and_synced_on_first_access(self):
  boot=probe.prepare_guest(ROOT/'evidence'/'genewars-1_1.exe')
  host=probe.DosHost(boot); host.allocations[7]=(0x200000,0x2000); boot.memory.ensure_size(0x202000)
  uc=probe.Uc(probe.UC_ARCH_X86,probe.UC_MODE_32); uc.mem_map(probe.SYNTH_ADDRESS,probe.PAGE,probe.UC_PROT_ALL)
  code=bytes.fromhex('a100012000c7052301200078563412a123012000f4')
  uc.mem_write(probe.SYNTH_ADDRESS,code)
  trace={}; probe.install_trace_hooks(uc,trace,100,host)
  uc.emu_start(probe.SYNTH_ADDRESS,0xffffffff,timeout=1_000_000,count=100)
  self.assertEqual(uc.reg_read(probe.UC_X86_REG_EAX),0x12345678)
  self.assertEqual(boot.memory.read(0x200100,4),bytes(4))
  self.assertEqual(boot.memory.read(0x200123,4),bytes.fromhex('78563412'))
  self.assertEqual(trace['guest_allocation_page_count'],1)
  self.assertEqual(trace['guest_allocation_first_page']['7'],'0x00200000')
  self.assertNotIn('unsupported_memory',trace)
