 def test_dpmi_dos_block_selector_is_installed_in_live_ldt(self):
  boot=probe.prepare_guest(ROOT/'evidence'/'genewars-1_1.exe')
  host=probe.DosHost(boot)
  host.dispatch(0x21,probe.CpuRegs(eax=0x4a00,ebx=0x7fff,es=boot.psp_segment))
  result=host.dispatch(0x31,probe.CpuRegs(eax=0x0100,ebx=0x1000))
  self.assertEqual(result.service,'dpmi31.allocate_dos_memory')
  uc=probe.Uc(probe.UC_ARCH_X86,probe.UC_MODE_32)
  uc.mem_map(0x1000,0xff000,probe.UC_PROT_ALL)
  self.assertTrue(probe.write_flat_gdt(uc,{},boot.psp_address))
  base,limit=probe.install_dos_selector(uc,host,0x24)
  desc=int.from_bytes(uc.mem_read(probe.LDT_ADDRESS+0x20,8),'little')
  decoded_base=((desc>>16)&0xffff)|(((desc>>32)&0xff)<<16)|(((desc>>56)&0xff)<<24)
  decoded_limit=(desc&0xffff)|(((desc>>48)&0xf)<<16)
  if (desc>>52)&0x8: decoded_limit=(decoded_limit<<12)|0xfff
  self.assertEqual((base,limit),(0x90000,0xffff))
  self.assertEqual((decoded_base,decoded_limit),(base,limit))
  host.dispatch(0x31,probe.CpuRegs(eax=0x0102,ebx=0x800,edx=0x24))
  probe.install_dos_selector(uc,host,0x24)
  desc=int.from_bytes(uc.mem_read(probe.LDT_ADDRESS+0x20,8),'little')
  self.assertEqual((desc&0xffff,((desc>>48)&0xf)),(0x7fff,0))
